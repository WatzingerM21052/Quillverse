// Embeds docs/spec/simulation-master-prompt-v3.md as a TS string constant so
// the Worker can include the full rules in every turn's context (§107-108 —
// the base rules are sent fresh each time, not assumed to survive in an
// external chat's memory).
//
// Drops sections describing the *old* markdown-file save format
// (BRIDGERTON_SIMULATION_STATE.md, §109-114) and first-session-only
// initialization instructions (§131-134, §171-172) — both are dead weight
// for every turn on an already-running game, and the save-format sections
// actively conflict with context-builder.ts's own JSON OUTPUT_FORMAT
// instructions. See docs/superpowers/plans/2026-08-15-master-prompt-slimming.md.
// Everything else (GM behavior/tone/world rules) stays verbatim, unedited —
// this is a mechanical, content-preserving cut, not a rewrite.
//
// Run: node scripts/embed-master-prompt.mjs

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const sourcePath = path.resolve(__dirname, '../../../docs/spec/simulation-master-prompt-v3.md');
const targetPath = path.resolve(__dirname, '../src/assets/master-prompt.ts');

const DROPPED_SECTIONS = new Set([109, 110, 111, 112, 114, 131, 132, 133, 134, 171, 172]);

const source = readFileSync(sourcePath, 'utf-8');
const lines = source.split('\n');

const headers = [];
lines.forEach((line, i) => {
  const match = line.match(/^# (\d+)\. /);
  if (match) headers.push({ num: Number(match[1]), line: i });
});
headers.push({ num: -1, line: lines.length });

const kept = [];
for (let i = 0; i < headers.length - 1; i++) {
  if (DROPPED_SECTIONS.has(headers[i].num)) continue;
  kept.push(lines.slice(headers[i].line, headers[i + 1].line).join('\n'));
}

const text = kept
  .join('\n')
  .replace(/^---\s*$/gm, '') // decorative section separators, no semantic content
  .replace(/\n{3,}/g, '\n\n') // collapse the blank-line runs that leaves behind
  .trim();

const output = `// Generated by scripts/embed-master-prompt.mjs from
// docs/spec/simulation-master-prompt-v3.md — do not hand-edit, regenerate instead.

export const MASTER_PROMPT_TEXT = ${JSON.stringify(text)};
`;

writeFileSync(targetPath, output, 'utf-8');
console.log(`Wrote ${targetPath} (${text.length} chars, source was ${source.length} chars)`);
